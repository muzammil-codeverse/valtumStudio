export function AdminIcon({
  name,
  className = "",
  size = 20
}: { name: string } & IconProps): React.JSX.Element | null {
  switch (name) {
    case "dashboard":
      return <DashboardIcon className={className} size={size} />;
    case "services":
      return <ServicesIcon className={className} size={size} />;
    case "projects":
      return <ProjectsIcon className={className} size={size} />;
    case "insights":
      return <InsightsIcon className={className} size={size} />;
    case "faqs":
      return <FaqsIcon className={className} size={size} />;
    case "navigation":
      return <NavigationIcon className={className} size={size} />;
    case "media":
      return <MediaIcon className={className} size={size} />;
    case "team":
      return <TeamIcon className={className} size={size} />;
    case "leads":
      return <LeadsIcon className={className} size={size} />;
    case "settings":
      return <SettingsIcon className={className} size={size} />;
    case "users":
      return <UsersIcon className={className} size={size} />;
    case "security":
      return <SecurityIcon className={className} size={size} />;
    case "sessions":
      return <SessionsIcon className={className} size={size} />;
    default:
      return null;
  }
}
